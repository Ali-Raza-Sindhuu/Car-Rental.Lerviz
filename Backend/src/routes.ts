apiRoutes.use(paymentRoutes);
apiRoutes.use(reviewRoutes);
apiRoutes.use('/admin/payments', paymentAdminRoutes);
apiRoutes.use('/admin/reviews', reviewAdminRoutes);
apiRoutes.use('/admin/maintenance', maintenanceAdminRoutes);
apiRoutes.use('/admin/coupons', couponAdminRoutes);
